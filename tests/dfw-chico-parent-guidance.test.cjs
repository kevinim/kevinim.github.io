'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs');
const {DISTRICT_REGISTRY}=require('../district-registry.js');
const {official}=require('../trusted-link-policy.js');
const {checkOfficialUrl}=require('../scripts/audit-gis-upload-links.cjs');
const {buildFromRepo}=require('../scripts/build-dfw-school-coverage-matrix.cjs');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const evidence=read('data/dfw-parent-source-chico-2026.json');
test('final Chico ISD parent inquiry is exact-host, source-dated, and non-enrollment-certified',()=>{
 const d=DISTRICT_REGISTRY[evidence.teaCode],m=buildFromRepo();
 const row=m.districts.find(x=>x.code==='249904');
 assert.ok(d&&row);assert.equal(evidence.teaCode,'249904');
 assert.equal(d.official,evidence.officialLandingUrl);
 assert.equal(d.officialNote,evidence.limitations);
 assert.equal(official(d.official),d.official);
 assert.equal(checkOfficialUrl(d.official),true);
 assert.equal(d.zoneKey,null);assert.equal(d.address,null);assert.equal(d.currency,null);
 assert.equal(d.campusIdMatch,false);assert.equal(d.lookupKind,'official-inquiry');
 assert.equal(row.parentGuidance.status,'registered-official-source');
 assert.equal(row.parentGuidance.lookupType,'official-inquiry');
 assert.equal(row.geometry.confirmedCurrentYear,false);
 assert.equal(row.teaCampusRecords,3);
 assert.equal(m.summary.publicISDsWithRegisteredParentRoute,108);
 assert.equal(m.summary.publicISDsMissingRegisteredParentRoute,0);
 assert.equal(m.summary.registeredParentRouteRatePublicISDPercent,100);
 assert.equal(m.summary.campusPolygonCoverageAllDFWPercent,null);
 assert.equal(m.summary.exactAddressAssignmentCoveragePercent,null);
 assert.match(d.officialNote,/2025/);
 assert.equal(evidence.currentYearRegistrationIndependentlyVerified,false);
 assert.equal(evidence.verifiedIndividualAddressAssignment,false);
 assert.equal(evidence.schoolAssignmentApiVerified,false);
 assert.equal(evidence.verifiedCurrentYearAttendanceGIS,false);
 assert.equal(evidence.personalAddressSubmitted,false);
 assert.equal(official('https://www.chicoisdtx.net.evil.example/enrollment'),null);
 assert.equal(checkOfficialUrl('https://www.chicoisdtx.net:444/enrollment'),false);
});
