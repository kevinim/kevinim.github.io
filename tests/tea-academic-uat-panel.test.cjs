'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const insights=require('../features/carrollton-school-insights.js');
const rated=require('../tea-ratings-2026.json').data;
const acc=require('../data/tea-accountability-2026-verified-batch.json');
const staar=require('../data/tea-staar-meets-2026-verified-batch.json');
const get=id=>rated.find(x=>x.id===id);
test('UAT data source year, record count and exact TEA campus source URLs fail closed',()=>{
  assert.equal(insights.validAcademicUrl(acc.source.url,'RATE'),true);
  assert.equal(insights.validAcademicUrl(acc.source.url,'D1_STAAR1'),false);
  assert.equal(insights.validAcademicUrl(staar.source.groups.D1_STAAR1.url,'D1_STAAR1'),true);
  assert.equal(insights.validAcademicUrl(staar.source.groups.D1_STAAR2.url,'D1_STAAR2'),true);
  assert.equal(insights.validAcademicUrl(staar.source.groups.D1_STAAR3.url,'D1_STAAR3'),true);
  assert.equal(insights.validAcademicUrl(acc.source.url.replace('rptsvr1.tea.texas.gov','rptsvr1.tea.texas.gov.attacker.com'),'RATE'),false);
  assert.equal(insights.validAcademicUrl(acc.source.url.replace('ccyy=2026','ccyy=2025'),'RATE'),false);
  assert.equal(insights.installAcademicBatches(acc,staar),2282);
  assert.equal(Object.keys(acc.campuses).length,2282);
  assert.equal(Object.keys(staar.campuses).length,2282);
});
test('numeric TEA 2026 domain and STAAR subject values connect to exact 9-digit school ID',()=>{
  assert.equal(insights.installAcademicBatches(acc,staar),2282);
  const allen=insights.getSchoolInsight(get('043901001'));
  assert.equal(allen.evidenceStatus,'reviewed');
  assert.deepEqual(allen.domains,{achievement:88,progress:80,gaps:93});
  assert.equal(allen.subjects.reading,75);
  assert.equal(allen.subjects.math,85);
  assert.equal(allen.subjects.science,43);
  assert.equal(allen.subjects.social,86,'socialStudies source key maps to UI social field');
  assert.equal(allen.academicDomainRows.length,3);
  assert.equal(allen.academicSubjectRows.length,4);
  assert.equal(allen.subjectsSource,staar.source.groups.D1_STAAR1.url);
  const kent=insights.getSchoolInsight(get('057903122'));
  assert.equal(kent.evidenceStatus,'reviewed','no longer unsourced narrative after official import');
  assert.equal(kent.domains.achievement,93);
  assert.match(kent.summary,/원인 분석이 아닙니다/);
});
test('Not Rated, missing subjects, and absent source rows cannot turn into zero or F',()=>{
  assert.equal(insights.installAcademicBatches(acc,staar),2282);
  const id=rated.find(x=>x.rating==='Not Rated'&&acc.campuses[x.id]?.studentAchievement?.status==='not-rated')?.id;
  assert.ok(id);
  const missing=insights.getSchoolInsight(get(id));
  assert.equal(missing.evidenceStatus,'rating-only');
  assert.equal(missing.domains,undefined);
  assert.ok(missing.academicDomainRows.some(x=>x.status==='not-rated'&&x.score===null));
  const noSocial=Object.entries(staar.campuses).find(([id,x])=>x.socialStudies.status==='unavailable')?.[0];
  assert.ok(noSocial);
  const lesson=insights.getSchoolInsight(get(noSocial));
  assert.equal(lesson.academicSubjectRows.find(x=>x.key==='socialStudies').status,'unavailable');
  assert.equal(lesson.subjects.social,undefined);
  const noSource=Object.entries(staar.campuses).find(([id,x])=>x.reading.status==='not-in-source')?.[0];
  assert.ok(noSource);
  assert.equal(insights.getSchoolInsight(get(noSource)).academicSubjectRows[0].status,'not-in-source');
});
test('tampered source ID, year, disguised URL, and suppressed numeric values reject entire batch',()=>{
  const bad=structuredClone(acc);
  bad.campuses['043901001'].districtId='000000';
  assert.equal(insights.installAcademicBatches(bad,staar),0);
  const badMetric=structuredClone(staar);
  const masked=Object.keys(badMetric.campuses).find(id=>badMetric.campuses[id].reading.status==='suppressed');
  assert.ok(masked);
  badMetric.campuses[masked].reading.value=0;
  assert.equal(insights.installAcademicBatches(acc,badMetric),0);
  assert.equal(insights.installAcademicBatches({...acc,schoolYear:'2024-25'},staar),0);
  assert.equal(insights.installAcademicBatches({...acc,source:{...acc.source,url:'https://evil.example'}},staar),0);
});
